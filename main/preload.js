const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (cb) => {
  const listener = (_e, ...args) => cb(...args);
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
};

contextBridge.exposeInMainWorld('deck', {
  getState: () => ipcRenderer.invoke('state:get'),
  setActive: (id) => ipcRenderer.invoke('ws:setActive', id),
  pickRepo: () => ipcRenderer.invoke('repo:pick'),
  inspectRepo: (dir) => ipcRenderer.invoke('repo:inspect', dir),
  setRepoLogo: (root, logo) => ipcRenderer.invoke('repo:setLogo', root, logo),
  listIcons: () => ipcRenderer.invoke('icons:list'),
  createWorkspace: (opts) => ipcRenderer.invoke('ws:create', opts),
  renameWorkspace: (id, name) => ipcRenderer.invoke('ws:rename', id, name),
  setWorkspaceTopic: (id, topic) => ipcRenderer.invoke('ws:setTopic', id, topic),
  setAutoName: (id, auto, name) => ipcRenderer.invoke('ws:setAutoName', id, auto, name),
  reorderWorkspaces: (ids) => ipcRenderer.invoke('ws:reorder', ids),
  removeWorkspace: (id) => ipcRenderer.invoke('ws:remove', id),
  startTerm: (id, kind, cols, rows) => ipcRenderer.invoke('term:start', id, kind, cols, rows),
  restartTerm: (id, kind, cols, rows, fresh) => ipcRenderer.invoke('term:restart', id, kind, cols, rows, fresh),
  write: (key, data) => ipcRenderer.send('term:write', key, data),
  killTerm: (key) => ipcRenderer.send('term:kill', key),
  notify: (opts) => ipcRenderer.invoke('notify', opts),
  onNotifyClick: on('notify:click'),
  rnNetStart: () => ipcRenderer.invoke('rnnet:start'),
  rnNetReconnect: () => ipcRenderer.invoke('rnnet:reconnect'),
  rnNetReload: () => ipcRenderer.invoke('rnnet:reload'),
  onRnNetEvent: on('rnnet:event'),
  onRnNetStatus: on('rnnet:status'),
  onRnConsole: on('rnnet:console'),
  activityList: () => ipcRenderer.invoke('activity:list'),
  activityClear: () => ipcRenderer.invoke('activity:clear'),
  onActivity: on('activity:event'),
  devList: () => ipcRenderer.invoke('dev:list'),
  devCapture: (id) => ipcRenderer.invoke('dev:capture', id),
  devSaveTemp: (id) => ipcRenderer.invoke('dev:saveTemp', id),
  devCopy: (id) => ipcRenderer.invoke('dev:copy', id),
  devSave: (id) => ipcRenderer.invoke('dev:save', id),
  devOpenUrl: (id, url) => ipcRenderer.invoke('dev:openUrl', id, url),
  devInput: (id, ev) => ipcRenderer.invoke('dev:input', id, ev),
  devOpenSimulator: () => ipcRenderer.invoke('dev:openSimulator'),
  resize: (key, cols, rows) => ipcRenderer.send('term:resize', key, cols, rows),
  gitInfo: (id) => ipcRenderer.invoke('git:info', id),
  gitChanges: (id, scope) => ipcRenderer.invoke('git:changes', id, scope),
  gitFileDiff: (id, scope, file) => ipcRenderer.invoke('git:fileDiff', id, scope, file),
  revertFile: (id, scope, file) => ipcRenderer.invoke('git:revert', id, scope, file),
  listDir: (id, rel) => ipcRenderer.invoke('fs:list', id, rel),
  readFile: (id, rel) => ipcRenderer.invoke('fs:read', id, rel),
  listFiles: (id) => ipcRenderer.invoke('fs:files', id),
  searchFiles: (id, opts) => ipcRenderer.invoke('fs:search', id, opts),
  cancelSearch: (id) => ipcRenderer.invoke('fs:searchCancel', id),
  findDefinition: (id, req) => ipcRenderer.invoke('code:definition', id, req),
  warmDefinitions: (id, file) => ipcRenderer.invoke('code:warm', id, file),
  fileStatus: (id) => ipcRenderer.invoke('fs:status', id),
  writeFile: (id, rel, text, expectMtime) => ipcRenderer.invoke('fs:write', id, rel, text, expectMtime),
  setDirty: (id, n) => ipcRenderer.send('editor:dirty', id, n),
  onMenuClose: on('menu:close'),
  openFile: (id, rel, line) => ipcRenderer.invoke('open:file', id, rel, line),
  getIcons: () => ipcRenderer.invoke('icons:manifest'),
  // Electron removed File.path; this is the supported way to get a dropped file's path.
  pathForFile: (file) => webUtils.getPathForFile(file),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  openPath: (id, how) => ipcRenderer.invoke('open:path', id, how),
  onTermData: on('term:data'),
  onTermExit: on('term:exit'),
  onStatus: on('ws:status'),
  onWorkspaceUpdated: on('ws:updated'),
  onFocusWorkspace: on('ws:focus'),
});
